/** 上一次抽中的文案（避免连续重复） */
let lastTitle = '';

/**
 * 随机抽取一条标题文案。
 * - 关闭「随机标题彩蛋」时固定返回 APP_TITLE
 * - 抽到与上一次相同的内容时重新抽取（最多重抽 5 次）
 */
export function pickRandomTitle(): string {
  const pool = TITLE_POOL.length > 0 ? TITLE_POOL : [APP_TITLE];
  if (!getConfig().randomTitle) {
    return APP_TITLE;
  }
  let next = pool[Math.floor(Math.random() * pool.length)];
  for (let i = 0; i < 5 && next === lastTitle && pool.length > 1; i++) {
    next = pool[Math.floor(Math.random() * pool.length)];
  }
  lastTitle = next;
  return next;
}

/** 清空上一次抽取记录（关闭彩蛋时调用，避免重新开启后与旧文案对比） */
export function resetRandomTitleState(): void {
  lastTitle = '';
}
